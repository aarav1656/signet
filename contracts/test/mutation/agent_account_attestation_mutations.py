#!/usr/bin/env python3
"""Mutation check for the attestation tests alone.

Usage (from contracts/):  python3 test/mutation/agent_account_attestation_mutations.py

Reuses the mutant list of agent_account_mutations.py and runs each selected mutant against ONLY the
new suites, so a KILLED row is attributable to them and not to the older unit tests:
  invariant  AgentAccountAttestationInvariant.t.sol invariant_only... (the fuzzed model)
  unit       AgentAccountAttestation.t.sol (the collateral admission path and the policy)
A mutant is KILLED when at least one test in that suite fails. The source is restored on exit and the
suites must go green again. Writes ../docs/security/agent-account-attestation-mutations.md.
"""
import importlib.util
import shutil
import subprocess
import sys
import time
from pathlib import Path

spec = importlib.util.spec_from_file_location("base", Path(__file__).with_name("agent_account_mutations.py"))
base = importlib.util.module_from_spec(spec)
spec.loader.exec_module(base)

RECORD = Path("../docs/security/agent-account-attestation-mutations.md")

INVARIANT = [
    "caller is agent",
    "agent unexpired",
    "not paused (agent)",
    "measurement approved",
    "agent != owner at registration",
    "unapproving the live measurement revokes",
    "revoke clears agent",
    "band 2 needs approval",
    "window checked on execute",
    "daily cap",
    "per-trade cap (approve)",
    "approve: proposer is current agent",
    "onlyOwner withdraw",
    "onlyOwner setLimits",
    "onlyOwner setMeasurement",
    "onlyOwner revokeAgent",
    "onlyOwner approveTrade",
    "onlyOwner openInferenceChannel",
    "onlyOwner rejectTrade",
    "onlyOwner setApprovalTtl",
    "onlyOwner pause",
    "onlyOwner setAttestationPolicy",
    "policy: change revokes the current agent",
    "plain admission closed while collateral is required",
]
UNIT = [
    "quote replay check (collateral path)",
    "plain admission closed while collateral is required",
    "collateral path: account re-checks the ceiling",
    "collateral path: owner's ceiling forwarded",
    "collateral path: owner's floor forwarded",
    "collateral path: status event",
    "policy: Revoked can never be accepted",
    "policy: change revokes the current agent",
    "policy: stores the flag",
    "policy: stores the ceiling",
    "policy: stores the floor",
    "onlyOwner setAttestationPolicy",
    "measurement approved",
    "agent != owner at registration",
]
SUITES = [
    ("invariant", INVARIANT, ["--match-path", "test/AgentAccountAttestationInvariant.t.sol", "--match-test", "invariant_"]),
    ("unit", UNIT, ["--match-path", "test/AgentAccountAttestation.t.sol"]),
]


def main():
    mutants = {n: (o, m) for n, o, m in base.MUTANTS}
    original = base.SRC.read_text()
    subprocess.run(["timeout", "230", "forge", "build"], env={**base.ENV, "FOUNDRY_PROFILE": "v4"}, check=True, capture_output=True)
    for d in ("cache-mut", "out-mut"):
        shutil.rmtree(d, ignore_errors=True)
    lines, survivors = [], 0
    try:
        for label, names, match in SUITES:
            base.CMD = ["timeout", "230", "forge", "test", *match]
            n, failed = base.run()
            if n != 0:
                sys.exit(f"{label}: baseline not green: {n} {failed}")
            print(f"{label}: baseline green", flush=True)
            for name in names:
                old, new = mutants[name]
                if original.count(old) != 1:
                    sys.exit(f"mutant '{name}': pattern found {original.count(old)} times")
                base.SRC.write_text(original.replace(old, new))
                t0 = time.time()
                n, failed = base.run()
                if n == 0:
                    n, failed = base.run(force=True)
                base.SRC.write_text(original)
                status = "KILLED" if n else ("ERROR" if n is None else "SURVIVED")
                survivors += status != "KILLED"
                line = f"{status:8} {label:9} {name:52} {', '.join(failed)}"
                lines.append(line)
                print(f"{line}  ({time.time() - t0:.0f}s)", flush=True)
            n, _ = base.run()
            print(f"{label}: restored suite {'green' if n == 0 else 'NOT GREEN'}", flush=True)
            if n != 0:
                survivors += 1
        killed = sum(1 for line in lines if line.startswith("KILLED"))
        tally = f"{killed}/{len(lines)} killed, {len(lines) - killed} survived or errored"
        print(tally)
        RECORD.write_text(
            "# Attestation tests: mutation record\n\n"
            "Generated by `contracts/test/mutation/agent_account_attestation_mutations.py` on "
            f"{time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}. Each guard in "
            "`contracts/src/AgentAccount.sol` is removed or weakened one at a time and only the new "
            "attestation suites are run: the fuzzed model (`invariant`) or the collateral admission and policy "
            "tests (`unit`). KILLED means a test in that suite failed; the source is then restored and the suite "
            f"must go green again.\n\nBaseline: green. {tally}.\n\n```\n" + "\n".join(lines) + "\n```\n"
        )
        sys.exit(1 if survivors else 0)
    finally:
        base.SRC.write_text(original)


if __name__ == "__main__":
    main()
