//! Exports two deterministic receipt vectors to `../fixtures/receipt_vectors.json`
//! so the Solidity side (`contracts/test/AssayReceipt.t.sol`, via forge's
//! `fs_permissions = [{ access = "read", path = "../fixtures" }]`, already
//! granted in `contracts/foundry.toml`) hardcodes the exact same
//! `requestedModelHash`/`servedModelHash`/`responseHash` bytes this crate's
//! own `verify_receipt_core` actually computed, not values invented
//! separately in each language. A fixed (non-random) Ed25519 key makes the
//! run reproducible; this test both re-generates the file and asserts its
//! own expectations every `cargo test`, so the fixture can never silently
//! drift from the code that produces it.
use ed25519_dalek::{Signer, SigningKey};
use receipt_verify::verify_receipt_core;
use std::io::Write as _;

fn keccak256(bytes: &[u8]) -> [u8; 32] {
    stylus_sdk::alloy_primitives::keccak256(bytes).0
}

fn hex32(b: [u8; 32]) -> String {
    format!("0x{}", hex::encode(b))
}

/// Same JCS-shaped receipt document layout as `receipt_verifier::json`'s
/// consumers expect (`api_version`, `event_log[].{type,model_id,result,body_hash}`,
/// top-level `model`) -- field order does not matter to this crate's
/// structural scanner, only well-formed JSON does.
fn build_doc(requested_model: &str, served_model: &str, response_hash_hex: &str) -> Vec<u8> {
    format!(
        r#"{{"api_version":"aci/1","chat_id":"chatcmpl-fixture","endpoint":"/v1/chat/completions","event_log":[{{"body_hash":"sha256:{req_hash}","type":"request.received"}},{{"model_id":"{served_model}","required":true,"result":"verified","session_id":"sess-fixture","type":"upstream.verified"}},{{"body_hash":"sha256:{resp_hash}","type":"response.returned"}}],"key_id":"phala-ed25519-fixture","method":"POST","model":"{requested_model}","receipt_id":"rcpt-fixture","served_at":1790000000,"workload_keyset_digest":"sha256:{req_hash}"}}"#,
        req_hash = "a".repeat(64),
        resp_hash = response_hash_hex,
        served_model = served_model,
        requested_model = requested_model,
    )
    .into_bytes()
}

#[test]
fn export_receipt_vectors_for_solidity() {
    // Fixed (not OsRng) key: reproducible pubkey/signature across every run
    // and every language reading this fixture.
    let key = SigningKey::from_bytes(&[0x42; 32]);
    let pubkey_hex = format!("0x{}", hex::encode(key.verifying_key().as_bytes()));

    // Case "honest": served model equals requested model -> pays.
    let honest_doc = build_doc("requested-model", "requested-model", &"bb".repeat(32));
    let honest_sig = key.sign(&honest_doc);
    let honest = verify_receipt_core(key.verifying_key().as_bytes(), &honest_doc, &honest_sig.to_bytes())
        .expect("honest fixture receipt must verify");
    assert_eq!(honest.requested_model_hash, honest.served_model_hash);
    assert_eq!(honest.requested_model_hash, keccak256(b"requested-model"));
    assert_eq!(honest.request_hash, [0xaa; 32]);
    assert_eq!(honest.response_hash, [0xbb; 32]);

    // Case "swap": served model differs from requested -> Assay.redeemWithReceipt
    // must revert ModelMismatch even though the signature itself is genuine.
    let swap_doc = build_doc("requested-model", "served-model", &"cc".repeat(32));
    let swap_sig = key.sign(&swap_doc);
    let swap = verify_receipt_core(key.verifying_key().as_bytes(), &swap_doc, &swap_sig.to_bytes())
        .expect("swap fixture receipt must verify (signature is genuine; only the field differs)");
    assert_ne!(swap.requested_model_hash, swap.served_model_hash);
    assert_eq!(swap.requested_model_hash, keccak256(b"requested-model"));
    assert_eq!(swap.served_model_hash, keccak256(b"served-model"));
    assert_eq!(swap.request_hash, [0xaa; 32]);
    assert_eq!(swap.response_hash, [0xcc; 32]);

    let json = format!(
        r#"{{
  "_comment": "Generated by receipt-verifier/tests/export_fixture.rs::export_receipt_vectors_for_solidity via verify_receipt_core (real Ed25519 verify + real JSON field extraction), not hand-computed. Re-run `cargo test --test export_fixture` in receipt-verifier/ to regenerate.",
  "pubkey": "{pubkey}",
  "honest": {{
    "receipt_bytes_hex": "0x{honest_doc_hex}",
    "signature_hex": "0x{honest_sig_hex}",
    "requested_model_hash": "{honest_req}",
    "served_model_hash": "{honest_served}",
    "request_hash": "{honest_rq}",
    "response_hash": "{honest_resp}"
  }},
  "model_swap": {{
    "receipt_bytes_hex": "0x{swap_doc_hex}",
    "signature_hex": "0x{swap_sig_hex}",
    "requested_model_hash": "{swap_req}",
    "served_model_hash": "{swap_served}",
    "request_hash": "{swap_rq}",
    "response_hash": "{swap_resp}"
  }}
}}
"#,
        pubkey = pubkey_hex,
        honest_doc_hex = hex::encode(&honest_doc),
        honest_sig_hex = hex::encode(honest_sig.to_bytes()),
        honest_req = hex32(honest.requested_model_hash),
        honest_served = hex32(honest.served_model_hash),
        honest_rq = hex32(honest.request_hash),
        honest_resp = hex32(honest.response_hash),
        swap_doc_hex = hex::encode(&swap_doc),
        swap_sig_hex = hex::encode(swap_sig.to_bytes()),
        swap_req = hex32(swap.requested_model_hash),
        swap_served = hex32(swap.served_model_hash),
        swap_rq = hex32(swap.request_hash),
        swap_resp = hex32(swap.response_hash),
    );

    let out_path = concat!(env!("CARGO_MANIFEST_DIR"), "/../fixtures/receipt_vectors.json");
    let mut f = std::fs::File::create(out_path).expect("create fixtures/receipt_vectors.json");
    f.write_all(json.as_bytes()).expect("write fixture");
}
